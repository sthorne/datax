// Sequences and enum types in schemas other than public (gap PG-D-035
// of docs/compatibility-gaps.md; design in docs/design/schemas.md).

// psqlDS is psql's \ds: \dt's query over the sequences.
var psqlDS = strings.Replace(psqlListQueries[`\dt`], "c.relkind IN ('r','p','')", "c.relkind IN ('S','')", 1)

// TestSchemaSequences: CREATE SEQUENCE in a schema, nextval / currval /
// setval / regclass through qualifiers and the search path, SERIAL and
// identity columns of a schema's table, SET SCHEMA of sequences and of
// the tables that own them, schema renames, DROP SEQUENCE and DROP
// SCHEMA, and the catalogs, from two nodes.
func TestSchemaSequences(t *testing.T) {
	tc := Start(t, 2)
	ctx, cancel := context.WithTimeout(context.Background(), 240*time.Second)
	defer cancel()
	a, b := pgConn(t, ctx, tc, 0), pgConn(t, ctx, tc, 1)

	mustExec(t, ctx, a, `CREATE SCHEMA s`)
	// CACHE 1: the values below do not depend on which gateway hands
	// them out.
	mustExec(t, ctx, a, `CREATE SEQUENCE q START 100 CACHE 1`) // public's, of the same name
	mustExec(t, ctx, a, `CREATE SEQUENCE s.q CACHE 1`)
	tempWantCode(t, ctx, a, `CREATE SEQUENCE s.q`, "42P07")
	mustExec(t, ctx, a, `CREATE SEQUENCE IF NOT EXISTS s.q`)
	tempWantCode(t, ctx, a, `CREATE SEQUENCE nosuch.q`, "3F000")
	schemaWant(t, ctx, b, `SELECT nextval('s.q')`, "1")
	schemaWant(t, ctx, b, `SELECT nextval('q')`, "100")
	schemaWant(t, ctx, b, `SELECT nextval('public.q')`, "101")
	schemaWant(t, ctx, b, `SELECT nextval('datax.s.q'), currval('s.q')`, "2|2")
	schemaWant(t, ctx, b, `SELECT setval('s.q', 10), nextval('s.q'::regclass)`, "10|11")
	schemaWant(t, ctx, a, `SELECT is_called FROM s.q`, "true")
	// regclass: off the path qualified, on it bare.
	schemaWant(t, ctx, a, `SELECT 's.q'::regclass::text, 'q'::regclass::text`, "s.q|q")
	mustExec(t, ctx, a, `SET search_path = s, public`)
	schemaWant(t, ctx, a, `SELECT nextval('q'), 's.q'::regclass::text, 'public.q'::regclass::text`, "12|q|public.q")
	// Created where the path says.
	mustExec(t, ctx, a, `CREATE SEQUENCE onpath`)
	mustExec(t, ctx, a, `RESET search_path`)
	schemaWant(t, ctx, a, `SELECT nextval('s.onpath')`, "1")
	tempWantCode(t, ctx, a, `SELECT nextval('onpath')`, "42P01")
	tempWantCode(t, ctx, a, `SELECT nextval('nosuch.q')`, "42P01")
	tempWantCode(t, ctx, a, `SELECT nextval('otherdb.s.q')`, "0A000")

	// SERIAL and identity columns: the sequence goes in the table's
	// schema, and the default names it there.
	mustExec(t, ctx, a, `CREATE TABLE s.t (id SERIAL PRIMARY KEY, v TEXT)`)
	mustExec(t, ctx, a, `CREATE TABLE s.ti (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v TEXT)`)
	mustExec(t, ctx, a, `CREATE TABLE t (id SERIAL PRIMARY KEY, v TEXT)`) // public's t_id_seq
	mustExec(t, ctx, a, `INSERT INTO s.t (v) VALUES ('a')`)
	mustExec(t, ctx, b, `INSERT INTO s.t (v) VALUES ('b')`)
	mustExec(t, ctx, b, `INSERT INTO s.ti (v) VALUES ('a')`)
	mustExec(t, ctx, b, `INSERT INTO t (v) VALUES ('public')`)
	schemaWant(t, ctx, a, `SELECT count(DISTINCT id) FROM s.t`, "2")
	schemaWant(t, ctx, a, `SELECT id FROM s.ti`, "1")
	schemaWant(t, ctx, a, `SELECT pg_get_serial_sequence('s.t', 'id'), pg_get_serial_sequence('s.ti', 'id'), pg_get_serial_sequence('t', 'id')`,
		"s.t_id_seq|s.ti_id_seq|public.t_id_seq")
	schemaWant(t, ctx, a, `SELECT table_schema || ':' || column_default FROM information_schema.columns
		WHERE table_name = 't' AND column_name = 'id' ORDER BY 1`, "public:nextval('t_id_seq'),s:nextval('s.t_id_seq')")
	// ADD COLUMN ... SERIAL and ADD GENERATED AS IDENTITY on a schema's
	// table.
	mustExec(t, ctx, a, `ALTER TABLE s.t ADD COLUMN n SERIAL`)
	mustExec(t, ctx, a, `CREATE TABLE s.late (id INT NOT NULL, v TEXT)`)
	mustExec(t, ctx, a, `ALTER TABLE s.late ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME s.late_ids)`)
	mustExec(t, ctx, a, `CREATE TABLE s.late2 (id INT NOT NULL)`)
	tempWantCode(t, ctx, a, `ALTER TABLE s.late2 ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.late2_ids)`, "0A000")
	mustExec(t, ctx, b, `INSERT INTO s.late (v) VALUES ('x')`)
	schemaWant(t, ctx, a, `SELECT id FROM s.late`, "1")
	schemaWant(t, ctx, a, `SELECT sequence_schema || '.' || sequence_name FROM information_schema.sequences ORDER BY 1`,
		"public.q,public.t_id_seq,s.onpath,s.q,s.t_id_seq,s.t_n_seq")

	// The catalogs: pg_class, pg_sequences, psql's \ds.
	schemaWant(t, ctx, a, `SELECT n.nspname || '.' || c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE c.relkind = 'S' ORDER BY 1`, "public.q,public.t_id_seq,s.late_ids,s.onpath,s.q,s.t_id_seq,s.t_n_seq,s.ti_id_seq")
	schemaWant(t, ctx, a, `SELECT schemaname || '.' || sequencename FROM pg_sequences WHERE sequencename = 'q' ORDER BY 1`, "public.q,s.q")
	schemaWant(t, ctx, a, psqlDS, "public|q|sequence|root,public|t_id_seq|sequence|root")
	mustExec(t, ctx, a, `SET search_path = s`)
	schemaWant(t, ctx, a, psqlDS, "s|late_ids|sequence|root,s|onpath|sequence|root,s|q|sequence|root,s|t_id_seq|sequence|root,s|t_n_seq|sequence|root,s|ti_id_seq|sequence|root")
	mustExec(t, ctx, a, `RESET search_path`)
	schemaWant(t, ctx, a, `SELECT pg_table_is_visible('s.q'::regclass), pg_table_is_visible('q'::regclass)`, "false|true")

	// ALTER SEQUENCE ... SET SCHEMA: a default bound to the sequence
	// follows it, and is rewritten to name it where it is.
	mustExec(t, ctx, a, `CREATE SCHEMA s2`)
	mustExec(t, ctx, a, `CREATE TABLE uses (id INT8 PRIMARY KEY DEFAULT nextval('s.q'), v TEXT)`)
	mustExec(t, ctx, a, `ALTER SEQUENCE s.q SET SCHEMA s2`)
	mustExec(t, ctx, b, `INSERT INTO uses (v) VALUES ('moved')`)
	schemaWant(t, ctx, a, `SELECT id FROM uses`, "13")
	schemaWant(t, ctx, a, `SELECT nextval('s2.q')`, "14")
	tempWantCode(t, ctx, a, `SELECT nextval('s.q')`, "42P01")
	schemaWant(t, ctx, a, `SELECT column_default FROM information_schema.columns WHERE table_name = 'uses' AND column_name = 'id'`, "nextval('s2.q')")
	mustExec(t, ctx, a, `CREATE SEQUENCE s.q`)
	tempWantCode(t, ctx, a, `ALTER SEQUENCE s.q SET SCHEMA s2`, "42P07")
	tempWantCode(t, ctx, a, `ALTER SEQUENCE s.t_id_seq SET SCHEMA s2`, "0A000")
	tempWantCode(t, ctx, a, `ALTER SEQUENCE s.q SET SCHEMA nosuch`, "3F000")
	mustExec(t, ctx, a, `ALTER SEQUENCE IF EXISTS s.nosuch SET SCHEMA s2`)
	mustExec(t, ctx, a, `ALTER SEQUENCE s.q SET SCHEMA s`) // already there

	// ALTER TABLE ... SET SCHEMA of a table owning sequences: they move
	// with it.
	mustExec(t, ctx, a, `ALTER TABLE s.t SET SCHEMA s2`)
	mustExec(t, ctx, b, `INSERT INTO s2.t (v) VALUES ('c')`)
	schemaWant(t, ctx, a, `SELECT count(DISTINCT id), count(DISTINCT n) FROM s2.t`, "3|3")
	schemaWant(t, ctx, a, `SELECT pg_get_serial_sequence('s2.t', 'id'), pg_get_serial_sequence('s2.t', 'n')`, "s2.t_id_seq|s2.t_n_seq")
	schemaWant(t, ctx, a, `SELECT column_default FROM information_schema.columns WHERE table_schema = 's2' AND table_name = 't' AND column_name = 'id'`, "nextval('s2.t_id_seq')")
	tempWantCode(t, ctx, a, `SELECT nextval('s.t_id_seq')`, "42P01")
	// A sequence of the owned one's name in the target is refused.
	mustExec(t, ctx, a, `CREATE SEQUENCE s.ti_id_seq2`)
	mustExec(t, ctx, a, `CREATE SEQUENCE s2.ti_id_seq`)
	tempWantCode(t, ctx, a, `ALTER TABLE s.ti SET SCHEMA s2`, "42P07")
	schemaWant(t, ctx, a, `SELECT pg_get_serial_sequence('s.ti', 'id')`, "s.ti_id_seq")
	// A table that owned no sequence before (pg_dump's OWNED BY) moves
	// its sequence too.
	mustExec(t, ctx, a, `CREATE TABLE dumped (id INT8 NOT NULL, v TEXT)`)
	mustExec(t, ctx, a, `CREATE SEQUENCE dumped_id_seq`)
	tempWantCode(t, ctx, a, `ALTER SEQUENCE s.onpath OWNED BY dumped.id`, "55000")
	tempWantCode(t, ctx, a, `CREATE SEQUENCE s.elsewhere OWNED BY dumped.id`, "55000")
	mustExec(t, ctx, a, `ALTER SEQUENCE dumped_id_seq OWNED BY dumped.id`)
	mustExec(t, ctx, a, `ALTER TABLE dumped ALTER COLUMN id SET DEFAULT nextval('public.dumped_id_seq'::regclass)`)
	mustExec(t, ctx, a, `ALTER TABLE dumped SET SCHEMA s2`)
	mustExec(t, ctx, b, `INSERT INTO s2.dumped (v) VALUES ('x')`)
	schemaWant(t, ctx, a, `SELECT id FROM s2.dumped`, "1")
	schemaWant(t, ctx, a, `SELECT sequence_schema FROM information_schema.sequences WHERE sequence_name = 'dumped_id_seq'`, "s2")

	// ALTER SCHEMA ... RENAME: the defaults keep drawing, and name the
	// schema by its new name.
	mustExec(t, ctx, a, `ALTER SCHEMA s2 RENAME TO s3`)
	mustExec(t, ctx, b, `INSERT INTO s3.t (v) VALUES ('d')`)
	mustExec(t, ctx, b, `INSERT INTO uses (v) VALUES ('renamed')`)
	schemaWant(t, ctx, a, `SELECT count(DISTINCT id) FROM s3.t`, "4")
	schemaWant(t, ctx, a, `SELECT id FROM uses WHERE v = 'renamed'`, "15")
	schemaWant(t, ctx, a, `SELECT column_default FROM information_schema.columns WHERE table_name = 'uses' AND column_name = 'id'`, "nextval('s3.q')")

	// DROP SEQUENCE of a sequence a default is bound to: RESTRICT
	// refuses, CASCADE drops the default.
	tempWantCode(t, ctx, a, `DROP SEQUENCE s3.q`, "2BP01")
	mustExec(t, ctx, a, `DROP SEQUENCE s3.q CASCADE`)
	tempWantCode(t, ctx, b, `INSERT INTO uses (v) VALUES ('no default')`, "23502")
	schemaWant(t, ctx, a, `SELECT count(*) FROM information_schema.columns WHERE table_name = 'uses' AND column_default IS NOT NULL`, "0")

	// DROP SCHEMA: a schema holding only a sequence, or only a type, is
	// not empty; CASCADE drops them.
	mustExec(t, ctx, a, `CREATE SCHEMA onlyseq`)
	mustExec(t, ctx, a, `CREATE SEQUENCE onlyseq.x`)
	tempWantCode(t, ctx, a, `DROP SCHEMA onlyseq`, "2BP01")
	mustExec(t, ctx, a, `CREATE SCHEMA onlytype`)
	mustExec(t, ctx, a, `CREATE TYPE onlytype.x AS ENUM ('a')`)
	tempWantCode(t, ctx, a, `DROP SCHEMA onlytype RESTRICT`, "2BP01")
	mustExec(t, ctx, a, `DROP SCHEMA onlyseq, onlytype CASCADE`)
	tempWantCode(t, ctx, b, `SELECT nextval('onlyseq.x')`, "42P01")
	schemaWant(t, ctx, a, `SELECT count(*) FROM pg_type WHERE typname = 'x'`, "0")
	// A sequence a default of another schema's table is bound to goes,
	// and the default with it.
	mustExec(t, ctx, a, `CREATE TABLE s.feeds (id INT8 DEFAULT nextval('s3.t_n_seq'))`)
	tempWantCode(t, ctx, a, `DROP TABLE s3.t`, "2BP01")
	mustExec(t, ctx, a, `DROP SCHEMA s3 CASCADE`)
	schemaWant(t, ctx, b, `SELECT count(*) FROM pg_class WHERE relnamespace = 's'::regnamespace AND relkind = 'S'`, "5")
	mustExec(t, ctx, b, `INSERT INTO s.feeds DEFAULT VALUES`)
	schemaWant(t, ctx, a, `SELECT id IS NULL FROM s.feeds`, "true")
	mustExec(t, ctx, a, `DROP SCHEMA s CASCADE`)
	schemaWant(t, ctx, b, `SELECT n.nspname || '.' || c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE c.relkind = 'S' ORDER BY 1`, "public.q,public.t_id_seq")
}

// TestSchemaEnumTypes: CREATE TYPE in a schema, columns and casts of
// it, ALTER TYPE ... ADD VALUE / SET SCHEMA, DROP TYPE and DROP
// SCHEMA, and the catalogs (pg_type, information_schema, format_type,
// psql's \dT).
func TestSchemaEnumTypes(t *testing.T) {
	tc := Start(t, 2)
	ctx, cancel := context.WithTimeout(context.Background(), 240*time.Second)
	defer cancel()
	a, b := pgConn(t, ctx, tc, 0), pgConn(t, ctx, tc, 1)

	mustExec(t, ctx, a, `CREATE SCHEMA s`)
	mustExec(t, ctx, a, `CREATE TYPE mood AS ENUM ('sad', 'ok')`) // public's, of the same name
	mustExec(t, ctx, a, `CREATE TYPE s.mood AS ENUM ('low', 'high')`)
	tempWantCode(t, ctx, a, `CREATE TYPE s.mood AS ENUM ('x')`, "42710")
	tempWantCode(t, ctx, a, `CREATE TYPE nosuch.mood AS ENUM ('x')`, "3F000")
	mustExec(t, ctx, a, `CREATE TABLE s.t (id INT PRIMARY KEY, m s.mood)`)
	mustExec(t, ctx, a, `CREATE TABLE t (id INT PRIMARY KEY, m mood)`)
	mustExec(t, ctx, b, `INSERT INTO s.t VALUES (1, 'high'), (2, 'low')`)
	mustExec(t, ctx, b, `INSERT INTO t VALUES (1, 'ok')`)
	tempWantCode(t, ctx, b, `INSERT INTO s.t VALUES (3, 'ok')`, "22P02")
	schemaWant(t, ctx, a, `SELECT m FROM s.t ORDER BY m`, "low,high")
	schemaWant(t, ctx, a, `SELECT 'high'::s.mood, 'ok'::mood, 'ok'::public.mood`, "high|ok|ok")
	tempWantCode(t, ctx, a, `SELECT 'ok'::s.mood`, "22P02")
	tempWantCode(t, ctx, a, `SELECT 'x'::nosuch.mood`, "42704")
	// Through the path, the schema's type comes first.
	mustExec(t, ctx, a, `SET search_path = s, public`)
	schemaWant(t, ctx, a, `SELECT 'low'::mood`, "low")
	mustExec(t, ctx, a, `CREATE TYPE onpath AS ENUM ('p')`)
	mustExec(t, ctx, a, `RESET search_path`)
	schemaWant(t, ctx, a, `SELECT 'p'::s.onpath`, "p")
	mustExec(t, ctx, a, `ALTER TYPE s.mood ADD VALUE 'top'`)
	mustExec(t, ctx, b, `INSERT INTO s.t VALUES (3, 'top')`)

	// The catalogs.
	schemaWant(t, ctx, a, `SELECT n.nspname || '.' || t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
		WHERE t.typtype = 'e' ORDER BY 1`, "public.mood,s.mood,s.onpath")
	schemaWant(t, ctx, a, `SELECT table_schema || ':' || udt_schema || '.' || udt_name FROM information_schema.columns
		WHERE table_name = 't' AND column_name = 'm' ORDER BY 1`, "public:public.mood,s:s.mood")
	schemaWant(t, ctx, a, `SELECT format_type(t.oid, NULL) FROM pg_type t WHERE t.typtype = 'e' ORDER BY t.typnamespace, 1`, "mood,s.mood,s.onpath")
	schemaWant(t, ctx, a, psqlListQueries[`\dT`], "public|mood|NULL")
	mustExec(t, ctx, a, `SET search_path = s`)
	schemaWant(t, ctx, a, psqlListQueries[`\dT`], "s|mood|NULL,s|onpath|NULL")
	mustExec(t, ctx, a, `RESET search_path`)
	schemaWant(t, ctx, a, `SELECT to_regtype('s.mood') IS NOT NULL, to_regtype('s.nosuch') IS NULL`, "true|true")

	// ALTER TYPE ... SET SCHEMA: the columns keep the type.
	mustExec(t, ctx, a, `CREATE SCHEMA s2`)
	mustExec(t, ctx, a, `ALTER TYPE s.mood SET SCHEMA s2`)
	mustExec(t, ctx, b, `INSERT INTO s.t VALUES (4, 'low')`)
	schemaWant(t, ctx, a, `SELECT 'top'::s2.mood`, "top")
	tempWantCode(t, ctx, a, `SELECT 'top'::s.mood`, "42704")
	schemaWant(t, ctx, a, `SELECT udt_schema FROM information_schema.columns WHERE table_schema = 's' AND table_name = 't' AND column_name = 'm'`, "s2")
	tempWantCode(t, ctx, a, `ALTER TYPE mood SET SCHEMA s2`, "42710")
	tempWantCode(t, ctx, a, `ALTER TYPE s.onpath SET SCHEMA nosuch`, "3F000")
	mustExec(t, ctx, a, `ALTER TYPE s2.mood SET SCHEMA s2`) // already there

	// DROP TYPE of a used type is refused; DROP SCHEMA ... CASCADE of
	// a schema whose type another schema's column uses is refused too.
	tempWantCode(t, ctx, a, `DROP TYPE s2.mood`, "2BP01")
	tempWantCode(t, ctx, a, `DROP SCHEMA s2 CASCADE`, "2BP01")
	// Its own tables' types go with it.
	mustExec(t, ctx, a, `ALTER TABLE s.t SET SCHEMA s2`)
	mustExec(t, ctx, a, `DROP SCHEMA s2 CASCADE`)
	schemaWant(t, ctx, b, `SELECT count(*) FROM pg_type WHERE typname = 'mood'`, "1")
	mustExec(t, ctx, a, `DROP SCHEMA s CASCADE`)
	schemaWant(t, ctx, b, `SELECT count(*) FROM pg_type WHERE typtype = 'e'`, "1")
}

// TestSchemaSequencePrivileges: creating a sequence or a type in a
// schema takes CREATE on it; using one (nextval, currval, setval, a
// cast to the type) takes USAGE on its schema, as a table does.
func TestSchemaSequencePrivileges(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 180*time.Second)
	defer cancel()
	tc := privCluster(t)
	root := pgConn(t, ctx, tc, 0)
	for _, stmt := range []string{
		`CREATE USER sp_alice`,
		`CREATE SCHEMA app`,
		`CREATE SEQUENCE app.ids`,
		`CREATE TYPE app.mood AS ENUM ('a', 'b')`,
		`GRANT USAGE, UPDATE ON SEQUENCE app.ids TO sp_alice`,
		`GRANT CREATE ON DATABASE datax TO sp_alice`,
	} {
		mustExec(t, ctx, root, stmt)
	}
	alice := scopeConn(t, ctx, tc, "sp_alice", "datax")
	// No CREATE on app: nothing is created in it.
	tempWantCode(t, ctx, alice, `CREATE SEQUENCE app.mine`, "42501")
	tempWantCode(t, ctx, alice, `CREATE TYPE app.mine AS ENUM ('x')`, "42501")
	tempWantCode(t, ctx, alice, `CREATE TABLE app.mine (id SERIAL)`, "42501")
	tempWantCode(t, ctx, alice, `ALTER SEQUENCE app.ids SET SCHEMA public`, "42501")
	// A grant on the sequence is not enough without USAGE on its
	// schema.
	tempWantCode(t, ctx, alice, `SELECT nextval('app.ids')`, "42501")
	tempWantCode(t, ctx, alice, `SELECT setval('app.ids', 5)`, "42501")
	tempWantCode(t, ctx, alice, `SELECT 'a'::app.mood`, "42501")
	// Nor does the path reach a schema without USAGE.
	mustExec(t, ctx, alice, `SET search_path = app, public`)
	tempWantCode(t, ctx, alice, `SELECT nextval('ids')`, "42P01")
	mustExec(t, ctx, alice, `RESET search_path`)
	mustExec(t, ctx, root, `GRANT USAGE ON SCHEMA app TO sp_alice`)
	schemaWant(t, ctx, alice, `SELECT nextval('app.ids')`, "1")
	schemaWant(t, ctx, alice, `SELECT 'b'::app.mood`, "b")
	tempWantCode(t, ctx, alice, `CREATE SEQUENCE app.mine`, "42501")
	mustExec(t, ctx, root, `GRANT CREATE ON SCHEMA app TO sp_alice`)
	mustExec(t, ctx, alice, `CREATE SEQUENCE app.mine`)
	mustExec(t, ctx, alice, `CREATE TYPE app.mine_t AS ENUM ('x')`)
	mustExec(t, ctx, alice, `CREATE TABLE app.mine_tab (id SERIAL PRIMARY KEY)`)
	mustExec(t, ctx, alice, `INSERT INTO app.mine_tab DEFAULT VALUES`)
	// GRANT ... ON ALL SEQUENCES IN SCHEMA reaches the schema's.
	mustExec(t, ctx, root, `CREATE USER sp_bob`)
	mustExec(t, ctx, root, `CREATE SEQUENCE app.other`)
	mustExec(t, ctx, root, `GRANT USAGE ON SCHEMA app TO sp_bob`)
	mustExec(t, ctx, root, `GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO sp_bob`)
	bob := scopeConn(t, ctx, tc, "sp_bob", "datax")
	schemaWant(t, ctx, bob, `SELECT nextval('app.other')`, "1")
	// REVOKE USAGE ON SCHEMA: refused again.
	mustExec(t, ctx, root, `REVOKE USAGE ON SCHEMA app FROM sp_bob`)
	tempWantCode(t, ctx, bob, `SELECT nextval('app.other')`, "42501")
}

// TestSchemaSequenceDefaultsBindAtCreation: a column default's
// nextval('name') draws from the sequence the name resolved to when the
// default was set, as PostgreSQL binds the regclass by OID: a sequence
// of the name created later in a schema earlier on an inserting
// session's path changes nothing, for a default set now or for one set
// before bindings existed (which resolves through public, as then).
func TestSchemaSequenceDefaultsBindAtCreation(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 180*time.Second)
	defer cancel()
	tc := privCluster(t)
	root := pgConn(t, ctx, tc, 0)
	for _, stmt := range []string{
		`CREATE SEQUENCE ids START 1`,
		`CREATE TABLE orders (id INT8 PRIMARY KEY DEFAULT nextval('ids'), v TEXT)`,
		`CREATE TABLE legacy (id INT8 PRIMARY KEY DEFAULT nextval('ids'), v TEXT)`,
		`CREATE TABLE ser (id SERIAL PRIMARY KEY, v TEXT)`,
		`CREATE USER sb_mallory`,
		`GRANT CREATE ON DATABASE datax TO sb_mallory`,
		`GRANT INSERT, SELECT ON orders, legacy, ser TO sb_mallory`,
		`GRANT USAGE ON SEQUENCE ids TO sb_mallory`,
	} {
		mustExec(t, ctx, root, stmt)
	}
	// legacy's default as a table made before bindings has it: no
	// seq_bindings in its descriptor.
	stripBindings(t, ctx, tc, "legacy")

	mallory := scopeConn(t, ctx, tc, "sb_mallory", "datax")
	mustExec(t, ctx, mallory, `CREATE SCHEMA sb_mallory`) // "$user" on mallory's default path
	mustExec(t, ctx, mallory, `CREATE SEQUENCE sb_mallory.ids START 1000`)
	mustExec(t, ctx, mallory, `CREATE SEQUENCE sb_mallory.ser_id_seq START 1000`)
	schemaWant(t, ctx, mallory, `SELECT nextval('ids')`, "1000") // the path's, for a statement
	mustExec(t, ctx, mallory, `INSERT INTO orders (v) VALUES ('m')`)
	mustExec(t, ctx, mallory, `INSERT INTO legacy (v) VALUES ('m')`)
	mustExec(t, ctx, mallory, `INSERT INTO ser (v) VALUES ('m')`)
	schemaWant(t, ctx, root, `SELECT id FROM orders`, "1")
	schemaWant(t, ctx, root, `SELECT id FROM legacy`, "2")
	schemaWant(t, ctx, root, `SELECT id FROM ser`, "1")
	// Root's own path, pointed at mallory's schema, changes nothing
	// either.
	mustExec(t, ctx, root, `SET search_path = sb_mallory, public`)
	mustExec(t, ctx, root, `INSERT INTO orders (v) VALUES ('r')`)
	mustExec(t, ctx, root, `INSERT INTO legacy (v) VALUES ('r')`)
	mustExec(t, ctx, root, `RESET search_path`)
	schemaWant(t, ctx, root, `SELECT max(id) FROM orders`, "3")
	schemaWant(t, ctx, root, `SELECT max(id) FROM legacy`, "4")
	// A default set while the path reaches mallory's schema binds to
	// mallory's sequence, and keeps it.
	mustExec(t, ctx, root, `SET search_path = sb_mallory, public`)
	mustExec(t, ctx, root, `CREATE TABLE theirs (id INT8 DEFAULT nextval('ids'))`)
	mustExec(t, ctx, root, `RESET search_path`)
	mustExec(t, ctx, root, `INSERT INTO sb_mallory.theirs DEFAULT VALUES`)
	schemaWant(t, ctx, root, `SELECT id FROM sb_mallory.theirs`, "1001")
	// CREATE TABLE ... LIKE ... INCLUDING DEFAULTS copies the binding.
	mustExec(t, ctx, root, `SET search_path = sb_mallory, public`)
	mustExec(t, ctx, root, `CREATE TABLE public.copy (LIKE public.orders INCLUDING DEFAULTS)`)
	mustExec(t, ctx, root, `RESET search_path`)
	mustExec(t, ctx, root, `INSERT INTO copy (v) VALUES ('c')`)
	schemaWant(t, ctx, root, `SELECT id FROM copy`, "5")
}

// stripBindings removes the sequence bindings of table name's column
// defaults, as a descriptor written before they existed has none.
func stripBindings(t *testing.T, ctx context.Context, tc *TestCluster, name string) {
	t.Helper()
	acc := catalog.NewAccessor()
	if err := tc.Nodes[0].DB().RunTxn(ctx, "strip-bindings", func(ctx context.Context, txn *kvclient.Txn) error {
		d, err := acc.LookupFreshIn(ctx, txn, catalog.DefaultDatabase, name)
		if err != nil {
			return err
		}
		c := d.Clone()
		found := false
		for i := range c.Columns {
			found = found || c.Columns[i].SeqBindings != nil
			c.Columns[i].SeqBindings = nil
		}
		if !found {
			t.Errorf("%s: no bindings to strip", name)
		}
		return acc.Update(ctx, txn, c)
	}); err != nil {
		t.Fatal(err)
	}
	// Every gateway reads the stripped descriptor once its lease (a
	// second, privCluster's) ends.
	time.Sleep(2500 * time.Millisecond)
}
