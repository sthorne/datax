// lookPgTools finds pg_dump ($DATAX_PG_DUMP, else on the PATH) and the
// pg_restore and psql beside it (else on the PATH), so the three are
// one release.
func lookPgTools() (pgDump, pgRestore, psql string, err error) {
	if p := os.Getenv("DATAX_PG_DUMP"); p != "" {
		pgDump, err = exec.LookPath(p)
	} else {
		pgDump, err = exec.LookPath("pg_dump")
	}
	if err != nil {
		return "", "", "", err
	}
	beside := func(name string) (string, error) {
		p := filepath.Join(filepath.Dir(pgDump), name)
		if _, serr := os.Stat(p); serr == nil {
			return p, nil
		}
		return exec.LookPath(name)
	}
	if pgRestore, err = beside("pg_restore"); err != nil {
		return "", "", "", err
	}
	if psql, err = beside("psql"); err != nil {
		return "", "", "", err
	}
	return pgDump, pgRestore, psql, nil
}

// TestPgDumpRestore runs PostgreSQL's own pg_dump against a cluster and
// restores what it writes into fresh clusters — the plain-SQL script
// through psql, the custom format through pg_restore, and a schema-only
// and data-only pair — then dumps each restored database and compares
// it with the source's dump: same schema, same data, same sequences,
// same large object, same grants. The custom-format dump also runs on a
// snapshot exported before a later insert, which it must not see.
// Skipped where pg_dump is not installed, unless DATAX_REQUIRE_PGDUMP
// is set (as in CI, whose runner image has PostgreSQL's client tools).
func TestPgDumpRestore(t *testing.T) {
	pgDump, pgRestore, psql, err := lookPgTools()
	if err != nil {
		if os.Getenv("DATAX_REQUIRE_PGDUMP") != "" {
			t.Fatalf("DATAX_REQUIRE_PGDUMP is set and pg_dump, pg_restore or psql is missing: %v", err)
		}
		t.Skipf("pg_dump, pg_restore or psql not installed: %v", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()
	if v, verr := exec.CommandContext(ctx, pgDump, "--version").CombinedOutput(); verr == nil {
		t.Logf("%s: %s", pgDump, strings.TrimSpace(string(v)))
	}
	dir := t.TempDir()
	run := func(what, bin string, args ...string) string {
		t.Helper()
		var stdout, stderr bytes.Buffer
		cmd := exec.CommandContext(ctx, bin, args...)
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		if err := cmd.Run(); err != nil || strings.Contains(stderr.String(), "ERROR") || strings.Contains(stderr.String(), "error:") {
			t.Fatalf("%s: %v\n%s%s", what, err, stderr.String(), stdout.String())
		}
		return stdout.String()
	}
	// A cluster with the large-object tables (a node makes them at start;
	// a test cluster has that loop off) and, for a target, the roles.
	start := func(target bool) string {
		tc := Start(t, 1)
		if _, err := sql.EnsureLargeObjectTables(ctx, tc.Nodes[0].DB(), catalog.NewAccessor()); err != nil {
			t.Fatal(err)
		}
		url := pgURL(tc, 0)
		if target {
			run("roles", psql, url, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-c", "CREATE ROLE reader", "-c", "CREATE USER alice PASSWORD 'pw'")
		}
		return url
	}
	file := func(name, content string) string {
		t.Helper()
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}
	// The dumps compare without psql's \restrict / \unrestrict lines,
	// whose key is random per dump.
	norm := func(dump string) string {
		var out []string
		for _, l := range strings.Split(dump, "\n") {
			if !strings.HasPrefix(l, `\restrict `) && !strings.HasPrefix(l, `\unrestrict `) {
				out = append(out, l)
			}
		}
		return strings.Join(out, "\n")
	}
	same := func(what, got, want string) {
		t.Helper()
		if norm(got) == norm(want) {
			return
		}
		g, w := strings.Split(norm(got), "\n"), strings.Split(norm(want), "\n")
		for i := 0; i < len(g) || i < len(w); i++ {
			var gl, wl string
			if i < len(g) {
				gl = g[i]
			}
			if i < len(w) {
				wl = w[i]
			}
			if gl != wl {
				t.Fatalf("%s: the restored database dumps differently from the source, from line %d:\n got: %q\nwant: %q\n\nrestored dump:\n%s", what, i+1, gl, wl, got)
			}
		}
	}

	src := start(false)
	run("schema", psql, src, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-f", file("schema.sql", pgDumpSchema))

	plain := run("pg_dump", pgDump, src)
	for _, w := range pgDumpWants {
		if !strings.Contains(plain, w) {
			t.Fatalf("pg_dump output lacks %q:\n%s", w, plain)
		}
	}
	schemaOnly := run("pg_dump --schema-only", pgDump, "--schema-only", src)
	dataOnly := run("pg_dump --data-only", pgDump, "--data-only", src)

	// A snapshot exported now, then a row the snapshot predates.
	conn, err := pgx.Connect(ctx, src)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = conn.Close(ctx) }()
	tx, err := conn.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	var snapshot string
	if err := tx.QueryRow(ctx, "SELECT pg_export_snapshot()").Scan(&snapshot); err != nil {
		t.Fatalf("pg_export_snapshot: %v", err)
	}
	run("insert", psql, src, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-c", "INSERT INTO ledger (note) VALUES ('after the snapshot')")
	custom := filepath.Join(dir, "dump.custom")
	run("pg_dump -Fc --snapshot", pgDump, "-Fc", "--snapshot="+snapshot, "-f", custom, src)
	_ = tx.Rollback(ctx)
	if after := run("pg_dump after the insert", pgDump, "--data-only", "-t", "ledger", src); !strings.Contains(after, "after the snapshot") {
		t.Fatalf("a dump without the snapshot lacks the later row:\n%s", after)
	}

	// The plain script, through psql.
	dst := start(true)
	run("psql restore", psql, dst, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-f", file("plain.sql", plain))
	same("plain restore", run("pg_dump of the plain restore", pgDump, dst), plain)

	// The custom format, through pg_restore.
	dst = start(true)
	run("pg_restore", pgRestore, "--exit-on-error", "-d", dst, custom)
	same("pg_restore of the snapshot's dump", run("pg_dump of the pg_restore", pgDump, dst), plain)

	// Schema first, then data.
	dst = start(true)
	run("psql restore of --schema-only", psql, dst, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-f", file("schema-only.sql", schemaOnly))
	run("psql restore of --data-only", psql, dst, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-f", file("data-only.sql", dataOnly))
	same("schema-only then data-only restore", run("pg_dump of the split restore", pgDump, dst), plain)
}
